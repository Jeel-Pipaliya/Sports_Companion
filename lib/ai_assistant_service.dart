import 'dart:async';

/// Model representing a chat message in the AI assistant conversation.
class ChatMessage {
  final String id;
  final String text;
  final bool isUser;
  final DateTime timestamp;
  final String engineUsed;
  final int latencyMs;
  final int tokensProcessed;
  final double confidenceScore;

  ChatMessage({
    required this.id,
    required this.text,
    required this.isUser,
    required this.timestamp,
    this.engineUsed = 'Gemini Nano (On-Device)',
    this.latencyMs = 15,
    this.tokensProcessed = 42,
    this.confidenceScore = 0.96,
  });

  Map<String, dynamic> toMap() {
    return {
      'id': id,
      'text': text,
      'isUser': isUser,
      'timestamp': timestamp.toIso8601String(),
      'engineUsed': engineUsed,
      'latencyMs': latencyMs,
      'tokensProcessed': tokensProcessed,
      'confidenceScore': confidenceScore,
    };
  }
}

