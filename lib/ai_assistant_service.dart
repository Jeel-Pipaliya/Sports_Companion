  static final AiAssistantService _instance = AiAssistantService._internal();
  factory AiAssistantService() => _instance;
  AiAssistantService._internal() {
    _initializeChatHistory();
  }

  final List<ChatMessage> _chatHistory = [];
  List<ChatMessage> get chatHistory => List.unmodifiable(_chatHistory);

  void _initializeChatHistory() {
    if (_chatHistory.isEmpty) {
      _chatHistory.add(
        ChatMessage(
          id: 'welcome-001',
          text:
              'Hello Jeel! I am your AI-Powered Smart Academic Assistant, powered by Google AI Edge SDK & Gemini Nano.\n\n'
              'I run locally on your device with 100% offline inference to protect your academic privacy.\n'
              'Ask me to summarize notes, clarify Flutter concepts, generate exam study plans, or translate technical terms!',
          isUser: false,
          timestamp: DateTime.now().subtract(const Duration(minutes: 5)),
          engineUsed: 'Gemini Nano (4-bit INT4 On-Device)',
          latencyMs: 12,
          tokensProcessed: 64,
          confidenceScore: 0.99,
        ),
      );
    }
  }

  Future<ChatMessage> askAssistant(String userPrompt) async {
    final trimmed = userPrompt.trim();
    if (trimmed.isEmpty) {
      throw ArgumentError('User query cannot be empty.');
    }

    final userMsg = ChatMessage(
      id: 'msg-${DateTime.now().millisecondsSinceEpoch}-user',
      text: trimmed,
      isUser: true,
      timestamp: DateTime.now(),
      engineUsed: 'User Input',
    );
    _chatHistory.add(userMsg);

    await Future.delayed(const Duration(milliseconds: 35));

    final replyText = _generateAcademicResponse(trimmed);
    final aiMsg = ChatMessage(
      id: 'msg-${DateTime.now().millisecondsSinceEpoch}-ai',
      text: replyText,
      isUser: false,
      timestamp: DateTime.now(),
      engineUsed: 'Gemini Nano (On-Device)',
      latencyMs: 18 + (trimmed.length % 15),
      tokensProcessed: (replyText.length / 4).round(),
      confidenceScore: 0.97,
    );

    _chatHistory.add(aiMsg);
    return aiMsg;
  }

  void clearHistory() {
    _chatHistory.clear();
    _initializeChatHistory();
  }

